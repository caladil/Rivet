//! **A fleet's certificate root, and its fleet server's certificate, minted on
//! the fleet server** — `ADR-063` §4.
//!
//! `cmd/rivet-initd` calls [`mint`] on the first boot of a fleet-root mode
//! fleet server's card, with the request the card carried
//! (`rivet_core::fleet_root`), the machine's own random source and its clock.
//! Nothing here writes anything: what comes back is PEM, and where it rests is
//! the caller's decision.
//!
//! Every later leaf is judged and issued by [`judge`], which `cmd/rivet-sysd`
//! calls: it judges with the root's certificate alone, and only its forked
//! issuing helper calls [`judge::issue_from_root`] with the root's key.
//!
//! # What is minted
//!
//! | | Signed by | Constrained to | Names |
//! | :-- | :-- | :-- | :-- |
//! | **root** | itself | the request's suffixes, and nothing else | none; its common name is the fleet |
//! | **server** | the root | inherits the root's constraint | `<host>.<suffix>` for every suffix |
//!
//! Every leaf, the server's included, is built by [`issue_leaf`], which says
//! what fields a leaf carries and why.
//!
//! **ECDSA P-256**, as `cmd/rivet-provision`'s `ca.rs` mints a
//! workstation root, and for its reason: a browser validates this chain, and
//! Chrome does not accept Ed25519 certificates.
//!
//! # The randomness, and where the keys come from
//!
//! **A random source that refuses stops the mint before any key exists.**
//! [`mint`] draws from the caller's source first and uses the bytes as the two
//! serial numbers; a source that refuses, or answers with the same byte
//! repeated — which no working generator produces in twenty bytes, and which a
//! stub filling a buffer does — mints nothing.
//!
//! The two private keys are generated by `rcgen` through `ring`'s system
//! generator, which on Linux is `getrandom(2)`: it blocks until the kernel's
//! pool is ready rather than returning weak bytes, and on a Raspberry Pi 4 the
//! hardware generator feeds that pool. `ring` offers no way to hand it bytes of
//! the caller's choosing, so the caller's source is the gate and the serials,
//! and the kernel's generator is the keys.
//!
//! # The clock
//!
//! A Raspberry Pi has no real-time clock, and first boot runs at the epoch
//! until `rivet-timed` corrects it (`ADR-021`). A validity window computed from
//! that clock would expire in 1980. So [`validity`] dates a window from the
//! issuing day, rounded down to its midnight UTC, to the same day the full
//! term later — unless the clock reads earlier than [`FLOOR_YEAR`], when the
//! window starts on the floor's first day. At the epoch a certificate runs
//! from the floor; on a machine whose clock is right it runs its whole term
//! from today, whatever the day of the year.

use rcgen::{
    BasicConstraints, CertificateParams, DistinguishedName, DnType, ExtendedKeyUsagePurpose,
    GeneralSubtree, IsCa, Issuer, KeyPair, KeyUsagePurpose, NameConstraints,
    PKCS_ECDSA_P256_SHA256, SerialNumber,
};
use rivet_core::fleet_root::Request;

pub mod judge;

/// The earliest year a validity window starts in. A clock reading earlier
/// than this is a clock nothing has set yet.
pub const FLOOR_YEAR: i32 = 2026;

/// How long the root lives, in years — `ca.rs`'s figure. An expired root makes
/// every page unreachable while the control plane keeps working, so a date far
/// enough away to be a non-event is worth more than renewal nobody runs.
pub const ROOT_YEARS: i32 = 10;

/// How long the server's certificate lives, in years — `ca.rs`'s figure.
pub const LEAF_YEARS: i32 = 5;

/// How many bytes are drawn for each serial number. RFC 5280 allows twenty
/// octets; the first is masked positive.
pub const SERIAL_BYTES: usize = 20;

/// A certificate and its private key.
///
/// **No `Debug`**: it holds a private key, and a panic message is a place a
/// key must never appear.
pub struct Pair {
    /// The certificate, PEM.
    pub certificate: String,
    /// The private key, PKCS#8 PEM. The only copy.
    pub key: String,
    /// The certificate, DER — what a fingerprint is taken over.
    pub certificate_der: Vec<u8>,
}

/// Everything one mint produces.
pub struct Minted {
    /// The fleet's root.
    pub root: Pair,
    /// The fleet server's certificate, signed by [`Minted::root`].
    pub server: Pair,
    /// The names [`Minted::server`] carries, in order; the first is its
    /// subject.
    pub names: Vec<String>,
}

/// Why nothing was minted.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Error {
    /// The random source refused, or answered in a way no generator does.
    Randomness(String),
    /// `rcgen` refused.
    Mint(String),
}

impl core::fmt::Display for Error {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            Self::Randomness(why) => write!(
                f,
                "no fleet root was minted, because this machine's random source did not answer \
                 as one: {why}"
            ),
            Self::Mint(why) => write!(f, "no fleet root was minted: {why}"),
        }
    }
}

impl From<rcgen::Error> for Error {
    fn from(e: rcgen::Error) -> Self {
        Self::Mint(e.to_string())
    }
}

/// **Mint the fleet's root and its server's certificate**, from `request`.
///
/// `random` is the machine's random source: `len` bytes or a reason. `now` is
/// the wall clock in seconds since the epoch, which may be the epoch itself.
///
/// # Errors
///
/// [`Error::Randomness`] before anything is generated; [`Error::Mint`] for
/// whatever `rcgen` refuses.
pub fn mint(
    request: &Request,
    random: &mut dyn FnMut(usize) -> Result<Vec<u8>, String>,
    now: u64,
) -> Result<Minted, Error> {
    let root_serial = serial(random)?;
    let server_serial = serial(random)?;
    let root_window = validity(now, ROOT_YEARS)?;
    let server_window = validity(now, LEAF_YEARS)?;

    let root_key = KeyPair::generate_for(&PKCS_ECDSA_P256_SHA256)?;
    let mut root_params = CertificateParams::default();
    root_params.distinguished_name = named(&request.fleet);
    root_params.serial_number = Some(root_serial);
    set_window(&mut root_params, root_window);
    // Path length 0: it signs its fleet's machines, and nothing it signs may
    // sign anything.
    root_params.is_ca = IsCa::Ca(BasicConstraints::Constrained(0));
    root_params.key_usages = vec![
        KeyUsagePurpose::KeyCertSign,
        KeyUsagePurpose::CrlSign,
        KeyUsagePurpose::DigitalSignature,
    ];
    root_params.name_constraints = Some(NameConstraints {
        permitted_subtrees: request
            .suffixes
            .iter()
            .map(|s| GeneralSubtree::DnsName(s.clone()))
            .collect(),
        excluded_subtrees: Vec::new(),
    });
    let root_certificate = root_params.clone().self_signed(&root_key)?;

    let names = request.names();
    let issuer = Issuer::new(root_params, &root_key);
    let server = issue_leaf_with_serial(&issuer, &names, server_serial, server_window)?;

    Ok(Minted {
        root: Pair {
            certificate: root_certificate.pem(),
            key: root_key.serialize_pem(),
            certificate_der: root_certificate.der().to_vec(),
        },
        server,
        names,
    })
}

/// **Issue one leaf from a fleet's root** — the one builder every certificate
/// a fleet-root machine issues goes through (`ADR-063` §4).
///
/// `issuer` is the root, `names` the DNS names the leaf answers to (the first
/// is also its subject), `random` and `now` as for [`mint`]. A new key is
/// generated for the leaf; nothing is written.
///
/// # The shape of every leaf
///
/// A chain engine that builds the path itself, rather than being handed the
/// root, finds the issuer by key identifier, and refuses a leaf whose purpose
/// it cannot read. So every leaf carries:
///
/// * an **authority key identifier** equal to the root's subject key
///   identifier, and its own **subject key identifier**;
/// * **basic constraints** saying it is not an authority;
/// * a critical **key usage** of `digitalSignature` alone — an ECDSA key signs
///   the handshake and does nothing else;
/// * an **extended key usage** of `serverAuth` and `clientAuth`. `serverAuth`
///   because it serves browsers and the proxy; `clientAuth` because the proxy
///   presents its own leaf to the applications behind it as its client
///   certificate (`ADR-046` §4), and a verifier that finds an extended key
///   usage without `clientAuth` refuses the caller.
///
/// # Errors
///
/// [`Error::Randomness`] before any key is generated; [`Error::Mint`] for an
/// empty name list or whatever `rcgen` refuses.
pub fn issue_leaf<S: rcgen::SigningKey>(
    issuer: &Issuer<'_, S>,
    names: &[String],
    random: &mut dyn FnMut(usize) -> Result<Vec<u8>, String>,
    now: u64,
) -> Result<Pair, Error> {
    let serial = serial(random)?;
    issue_leaf_with_serial(issuer, names, serial, validity(now, LEAF_YEARS)?)
}

/// Write `window` into `params`, each end at its day's midnight UTC.
fn set_window(params: &mut CertificateParams, (start, end): (Day, Day)) {
    params.not_before = rcgen::date_time_ymd(start.year, start.month, start.day);
    params.not_after = rcgen::date_time_ymd(end.year, end.month, end.day);
}

/// [`issue_leaf`], with its serial already drawn — so [`mint`] can draw both
/// of its serials before it generates any key.
fn issue_leaf_with_serial<S: rcgen::SigningKey>(
    issuer: &Issuer<'_, S>,
    names: &[String],
    serial: SerialNumber,
    window: (Day, Day),
) -> Result<Pair, Error> {
    let Some(subject) = names.first() else {
        return Err(Error::Mint("no name was given for the leaf".to_owned()));
    };
    let key = KeyPair::generate_for(&PKCS_ECDSA_P256_SHA256)?;
    let mut params = CertificateParams::new(names.to_vec())?;
    params.distinguished_name = named(subject);
    params.serial_number = Some(serial);
    set_window(&mut params, window);
    // `ExplicitNoCa` rather than `NoCa`: it is what writes the subject key
    // identifier, and it states in the certificate that this is no authority.
    params.is_ca = IsCa::ExplicitNoCa;
    params.use_authority_key_identifier_extension = true;
    params.key_usages = vec![KeyUsagePurpose::DigitalSignature];
    params.extended_key_usages = vec![
        ExtendedKeyUsagePurpose::ServerAuth,
        ExtendedKeyUsagePurpose::ClientAuth,
    ];
    let certificate = params.signed_by(&key, issuer)?;
    Ok(Pair {
        certificate: certificate.pem(),
        key: key.serialize_pem(),
        certificate_der: certificate.der().to_vec(),
    })
}

/// The SHA-256 of a certificate's DER, lower-case hex — the fingerprint a
/// trust store shows beside a root.
#[must_use]
pub fn fingerprint(der: &[u8]) -> String {
    let digest = ring::digest::digest(&ring::digest::SHA256, der);
    digest.as_ref().iter().map(|b| format!("{b:02x}")).collect()
}

/// The DER inside one PEM certificate, or `None` when `pem` is not one.
#[must_use]
pub fn der_of_pem(pem: &str) -> Option<Vec<u8>> {
    let body = pem
        .split("-----BEGIN CERTIFICATE-----")
        .nth(1)?
        .split("-----END CERTIFICATE-----")
        .next()?;
    let joined: String = body.chars().filter(|c| !c.is_whitespace()).collect();
    rivet_core::base64::decode(&joined)
}

/// One calendar day, UTC — an end of a validity window, at its midnight.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Day {
    pub year: i32,
    pub month: u8,
    pub day: u8,
}

/// The last year a certificate date can name (`GeneralizedTime`'s four
/// digits, and the range `rcgen` accepts).
const LAST_YEAR: i32 = 9999;

/// **The validity window of a certificate issued at `now` that lives
/// `years`**: from the issuing day's midnight UTC to the same day `years`
/// later. A clock reading earlier than [`FLOOR_YEAR`] is a clock nothing has
/// set yet, and the window starts on the floor's first day instead, so a
/// board at the epoch still issues a certificate that is valid once its clock
/// is right. A window starting on 29 February ends on 1 March when the end
/// year has no 29 February, so it is never shorter than `years`.
///
/// # Errors
///
/// [`Error::Mint`] for a clock so far ahead that the end cannot be written as
/// a certificate date — refused rather than a panic, because PID 1 links this.
pub fn validity(now: u64, years: i32) -> Result<(Day, Day), Error> {
    let days = i64::try_from(now / 86_400).unwrap_or(i64::MAX);
    let (year, month, day) = civil_from_days(days);
    let start = match i32::try_from(year) {
        Ok(year) if year < FLOOR_YEAR => Day { year: FLOOR_YEAR, month: 1, day: 1 },
        Ok(year) if year <= LAST_YEAR - years => Day { year, month, day },
        _ => {
            return Err(Error::Mint(format!(
                "the clock reads {now} seconds since the epoch, past any date a certificate \
                 lasting {years} years can end on"
            )));
        }
    };
    let end_year = start.year + years;
    let end = if start.month == 2 && start.day == 29 && !is_leap(end_year) {
        Day { year: end_year, month: 3, day: 1 }
    } else {
        Day { year: end_year, ..start }
    };
    Ok((start, end))
}

fn is_leap(year: i32) -> bool {
    (year % 4 == 0 && year % 100 != 0) || year % 400 == 0
}

/// A proleptic Gregorian date from days since 1970-01-01 — Howard Hinnant's
/// `civil_from_days`, the inverse of `judge`'s `days_from_civil`.
fn civil_from_days(days: i64) -> (i64, u8, u8) {
    let z = days.saturating_add(719_468);
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = doy - (153 * mp + 2) / 5 + 1;
    let month = if mp < 10 { mp + 3 } else { mp - 9 };
    let year = yoe + era * 400 + i64::from(month <= 2);
    (
        year,
        u8::try_from(month).unwrap_or(1),
        u8::try_from(day).unwrap_or(1),
    )
}

/// One serial number from the caller's source, refused if the source refuses
/// or answers with one byte repeated.
fn serial(random: &mut dyn FnMut(usize) -> Result<Vec<u8>, String>) -> Result<SerialNumber, Error> {
    let mut bytes = random(SERIAL_BYTES).map_err(Error::Randomness)?;
    if bytes.len() != SERIAL_BYTES {
        return Err(Error::Randomness(format!(
            "{SERIAL_BYTES} bytes were asked for and {} came back",
            bytes.len()
        )));
    }
    if bytes.iter().all(|b| *b == bytes[0]) {
        return Err(Error::Randomness(format!(
            "{SERIAL_BYTES} bytes came back all {:#04x}, which is a stub filling a buffer and \
             not a generator",
            bytes[0]
        )));
    }
    // Positive, and never a leading zero octet that DER would strip.
    bytes[0] = (bytes[0] & 0x7f) | 0x01;
    Ok(SerialNumber::from(bytes))
}

fn named(common: &str) -> DistinguishedName {
    let mut dn = DistinguishedName::new();
    dn.push(DnType::CommonName, common);
    dn
}

