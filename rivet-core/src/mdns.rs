//! **What the mDNS responder is handed** — `ADR-017` §3.
//!
//! `rivet-mdnsd` runs under its own identity and may read neither the machine
//! document nor the DHCP leases, which are root's. The supervisor instead
//! writes it a projection of exactly what it announces from: the machine's
//! name, and every interface the document's `[network]` table names with the
//! address it holds — as written for a static interface, from the lease for a
//! DHCP one — or, for a DHCP interface with no lease yet, the fact that it is
//! still waiting for one. The supervisor already computes exactly this to
//! decide when the responder must be restarted, so the projection is that
//! computation written down rather than a second one.
//!
//! The file lives in the service's home on [`crate::name_service`]'s footing:
//! `<volume>/app/<name>` is root-owned at `0755`, so the service cannot plant a
//! link where root is about to write, and it cannot rewrite what it announces.
//!
//! # Why it is not a configuration document
//!
//! The name service's projection is a valid configuration document, read by
//! the document's own parser. This one cannot be: a leased address is what the
//! machine *is*, and the configuration document holds only what it *should
//! be* (`ADR-007` §3), so it has no field a lease could go in. The format
//! here is [`crate::settings`]' instead — one line per fact, `key=value`, a
//! writer and a strict reader side by side in this module.
//!
//! # The format
//!
//! ```text
//! # (a generated header)
//! hostname=kitchen-pi
//! address=eth0 192.168.1.50
//! leaseless=wlan0
//! end
//! ```
//!
//! * `hostname=` at most once, absent when the machine has no name.
//! * `address=<interface> <IPv4 address>` for each interface with an address.
//! * `leaseless=<interface>` for each DHCP interface with no lease yet.
//! * **`end`, last.** The supervisor rewrites this file in place while the
//!   responder may be reading it, so a reader can meet a file that is empty or
//!   cut short. Without the terminator a file cut after its first interface
//!   reads as a valid machine with one interface, and the responder would
//!   announce an address it should have refused as ambiguous. With it, a short
//!   file is [`ParseError::Incomplete`] and never a smaller answer.

use core::net::Ipv4Addr;

use crate::hostname::Hostname;

/// The file's name, inside the service's home.
pub const FILE: &str = "mdns";

/// `<volume>/app/<name>/mdns` — **root-owned, readable by the service.**
#[must_use]
pub fn path(volume: &str, name: &crate::service::ServiceName) -> String {
    format!("{}/{FILE}", crate::service::app_dir(volume, name))
}

/// The mode the projection is written with — `0644`, root-owned, for
/// [`crate::name_service::MODE`]'s reason. It holds a name and addresses the
/// machine announces to its whole link anyway.
pub const MODE: u32 = 0o644;

/// The line that closes a complete projection.
pub const END: &str = "end";

/// What the responder announces from.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Projection {
    /// The machine's name, as the supervisor settled it, or `None` when it has
    /// none.
    pub hostname: Option<Hostname>,
    /// Every interface with an address, and that address, in document order.
    pub addressed: Vec<(String, Ipv4Addr)>,
    /// Every DHCP interface with no lease yet, in document order.
    pub leaseless: Vec<String>,
}

/// Why a projection could not be read.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ParseError {
    /// The file does not end with [`END`]: it is being written, or a write
    /// was cut short. A moment rather than a state, so a reader may wait.
    Incomplete,
    /// A line this format does not hold. The supervisor never writes one, so
    /// this is a file something else wrote, and it is refused rather than
    /// read in part.
    Malformed {
        /// One-based.
        line: usize,
        text: String,
        why: &'static str,
    },
}

impl core::fmt::Display for ParseError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            Self::Incomplete => write!(
                f,
                "the projection does not end with `{END}`, so it is being written or a write was \
                 cut short"
            ),
            Self::Malformed { line, text, why } => {
                write!(f, "line {line} of the projection, `{text}`, is refused: {why}")
            }
        }
    }
}

impl core::error::Error for ParseError {}

impl Projection {
    /// Render the file. Total: every value here has one line that holds it.
    #[must_use]
    pub fn render(&self) -> String {
        let mut out = String::from(
            "# Generated by Rivet for rivet-mdnsd: this machine's name, and the address of every\n\
             # interface the [network] table of the configuration document names - as written\n\
             # for a static interface, from its lease for a DHCP one. Do not edit: this is a\n\
             # view, never an interface (ADR-007 §3).\n",
        );
        if let Some(name) = &self.hostname {
            out.push_str("hostname=");
            out.push_str(name.as_str());
            out.push('\n');
        }
        for (interface, address) in &self.addressed {
            out.push_str(&format!("address={interface} {address}\n"));
        }
        for interface in &self.leaseless {
            out.push_str(&format!("leaseless={interface}\n"));
        }
        out.push_str(END);
        out.push('\n');
        out
    }

    /// Read the file back, strictly.
    ///
    /// # Errors
    ///
    /// [`ParseError::Incomplete`] when the file does not end with [`END`],
    /// and [`ParseError::Malformed`] for any line this format does not hold.
    pub fn parse(text: &str) -> Result<Self, ParseError> {
        let mut out = Self::default();
        let mut ended = false;
        let mut named = false;
        for (index, raw) in text.lines().enumerate() {
            let line = raw.trim_end_matches('\r');
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let malformed = |why: &'static str| ParseError::Malformed {
                line: index + 1,
                text: line.to_string(),
                why,
            };
            if ended {
                return Err(malformed("nothing may follow `end`"));
            }
            if line == END {
                ended = true;
                continue;
            }
            let Some((key, value)) = line.split_once('=') else {
                return Err(malformed("a line is `key=value`, `end`, or a comment"));
            };
            match key {
                "hostname" => {
                    if named {
                        return Err(malformed("the machine has one name"));
                    }
                    named = true;
                    out.hostname = Some(
                        Hostname::new(value).ok_or_else(|| malformed("not a hostname"))?,
                    );
                }
                "address" => {
                    let Some((interface, address)) = value.split_once(' ') else {
                        return Err(malformed("an address line is `<interface> <IPv4 address>`"));
                    };
                    let interface = interface_name(interface).ok_or_else(|| malformed("not an interface name"))?;
                    let address: Ipv4Addr = address
                        .parse()
                        .map_err(|_| malformed("not an IPv4 address"))?;
                    if out.names(interface) {
                        return Err(malformed("an interface appears once"));
                    }
                    out.addressed.push((interface.to_string(), address));
                }
                "leaseless" => {
                    let interface = interface_name(value).ok_or_else(|| malformed("not an interface name"))?;
                    if out.names(interface) {
                        return Err(malformed("an interface appears once"));
                    }
                    out.leaseless.push(interface.to_string());
                }
                _ => return Err(malformed("not a key this projection holds")),
            }
        }
        if ended { Ok(out) } else { Err(ParseError::Incomplete) }
    }

    fn names(&self, interface: &str) -> bool {
        self.addressed.iter().any(|(name, _)| name == interface)
            || self.leaseless.iter().any(|name| name == interface)
    }
}

/// An interface name as the kernel allows one: 1 to 15 bytes, none of them
/// whitespace, `/` or `=`.
fn interface_name(text: &str) -> Option<&str> {
    let ok = !text.is_empty()
        && text.len() <= 15
        && !text.bytes().any(|b| b.is_ascii_whitespace() || b == b'/' || b == b'=' || b.is_ascii_control());
    ok.then_some(text)
}

#[cfg(test)]
mod tests {
    #![allow(clippy::expect_used, clippy::panic, clippy::unwrap_used)]

    use super::*;

    fn two_interfaces() -> Projection {
        Projection {
            hostname: Hostname::new("kitchen-pi"),
            addressed: vec![("eth0".to_string(), Ipv4Addr::new(192, 168, 1, 50))],
            leaseless: vec!["wlan0".to_string()],
        }
    }

    #[test]
    fn the_projection_sits_in_the_services_home_beside_its_settings() {
        let name = crate::service::ServiceName::new(crate::service::MDNSD_SERVICE_NAME).unwrap();
        assert_eq!(path("/state", &name), "/state/app/rivet-mdnsd/mdns");
        assert_eq!(
            std::path::Path::new(&path("/state", &name)).parent(),
            std::path::Path::new(&crate::settings::path("/state", &name)).parent(),
        );
    }

    #[test]
    fn the_mode_is_readable_by_the_service_and_writable_only_by_root() {
        assert_eq!(MODE & 0o044, 0o044);
        assert_eq!(MODE & 0o022, 0);
    }

    /// The writer's text, as it is, and the reader agreeing with it.
    #[test]
    fn a_projection_renders_one_line_per_fact_and_reads_back_unchanged() {
        let text = two_interfaces().render();
        let lines: Vec<&str> = text.lines().filter(|l| !l.starts_with('#')).collect();
        assert_eq!(
            lines,
            ["hostname=kitchen-pi", "address=eth0 192.168.1.50", "leaseless=wlan0", "end"]
        );
        assert_eq!(Projection::parse(&text), Ok(two_interfaces()));
    }

    /// A nameless machine with no interfaces is a projection too, and says so.
    #[test]
    fn an_empty_projection_is_still_complete() {
        let text = Projection::default().render();
        assert_eq!(Projection::parse(&text), Ok(Projection::default()));
    }

    /// **The reason `end` exists.** Every prefix of a complete file that stops
    /// short of `end` is refused as incomplete, never read as a smaller
    /// machine: a file cut after its first of two addresses would otherwise
    /// announce the one address it should have refused as ambiguous.
    #[test]
    fn every_file_cut_short_is_incomplete_and_never_a_smaller_answer() {
        let full = Projection {
            hostname: Hostname::new("kitchen-pi"),
            addressed: vec![
                ("eth0".to_string(), Ipv4Addr::new(10, 0, 0, 2)),
                ("wlan0".to_string(), Ipv4Addr::new(10, 0, 1, 2)),
            ],
            leaseless: Vec::new(),
        }
        .render();
        let complete_at = full.rfind(END).expect("an end line");
        for cut in (0..complete_at).filter(|&cut| full.is_char_boundary(cut)) {
            match Projection::parse(&full[..cut]) {
                Err(ParseError::Incomplete) => {}
                // A cut inside a line can leave a fragment that is malformed;
                // that is refused too, and is never an answer.
                Err(ParseError::Malformed { .. }) => {}
                Ok(read) => panic!("{cut} bytes read as {read:?}"),
            }
        }
        assert!(Projection::parse("").is_err_and(|e| e == ParseError::Incomplete));
    }

    #[test]
    fn anything_after_end_is_refused() {
        let text = format!("{}address=eth1 10.0.0.9\n", two_interfaces().render());
        assert!(matches!(Projection::parse(&text), Err(ParseError::Malformed { .. })));
    }

    #[test]
    fn a_line_this_format_does_not_hold_is_refused_by_line_number() {
        for bad in [
            "gateway=10.0.0.1",
            "address=eth0",
            "address=eth0 not-an-address",
            "address= 10.0.0.2",
            "hostname=not a name",
            "leaseless=",
            "leaseless=has space",
            "no equals sign",
        ] {
            let text = format!("# header\n{bad}\nend\n");
            match Projection::parse(&text) {
                Err(ParseError::Malformed { line, text, .. }) => {
                    assert_eq!(line, 2, "{bad}");
                    assert_eq!(text, bad);
                }
                other => panic!("{bad}: {other:?}"),
            }
        }
    }

    #[test]
    fn a_second_name_or_a_repeated_interface_is_refused() {
        for bad in [
            "hostname=a\nhostname=b\n",
            "address=eth0 10.0.0.2\naddress=eth0 10.0.0.3\n",
            "address=eth0 10.0.0.2\nleaseless=eth0\n",
        ] {
            let text = format!("{bad}end\n");
            assert!(
                matches!(Projection::parse(&text), Err(ParseError::Malformed { .. })),
                "{bad}"
            );
        }
    }

    /// The header and blank lines are not facts, and a CRLF file reads the
    /// same as an LF one.
    #[test]
    fn comments_blank_lines_and_carriage_returns_are_not_facts() {
        let text = "# one\r\n\r\nhostname=kitchen-pi\r\n# two\r\nend\r\n";
        assert_eq!(
            Projection::parse(text),
            Ok(Projection {
                hostname: Hostname::new("kitchen-pi"),
                ..Projection::default()
            })
        );
    }
}
