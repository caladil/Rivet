/// Perform it.
///
/// # Errors
///
/// If a second word was given, or the kernel's uptime could not be read. **A
/// journal that could not be read is not an error** — the boots are reported as
/// unmeasured and the uptime still answers.
pub(super) fn perform(
    arguments: &[&str],
    observed: &mut dyn Observed,
) -> Result<Value, OperationError> {
    if let Some(extra) = arguments.get(1) {
        return Err(OperationError::about(
            ErrorCode::Arguments,
            SUBJECT,
            format!(
                "`{SUBJECT}` takes no second word and {extra:?} is one. If you meant to select a \
                 boot of the JOURNAL, that is `{}` — this subject is about the boot that is \
                 running.",
                super::log::SUBJECT
            ),
        ));
    }

    let read = observed.read_boot().map_err(|e| {
        OperationError::about(ErrorCode::MachineRefused, SUBJECT, e.why().to_string())
    })?;

    // **The journal is asked second and its failure is not fatal.** A machine
    // whose `/state` never mounted still knows how long it has been up, and an
    // answer that refused would withhold the half it has.
    let boots = observed.read_journal().map(|journal| {
        // `parse_lines`'s refusals are dropped here on purpose: a line this
        // build cannot parse carries no boot identifier, and `get log` is the
        // subject that reports how many there were. Counting them twice, in two
        // subjects, is the duplication this module is about avoiding.
        let (records, _) = crate::journal::parse_lines(journal.lines.iter().map(String::as_str));
        crate::journal::boots_in_order(&records)
    });

    let mut fields = vec![("subject", Value::str(SUBJECT))];
    if let Some(id) = &read.boot_id {
        fields.push(("boot_id", Value::str(id.clone())));
    } else if let Some(why) = &read.boot_id_unmeasured {
        fields.push(("boot_id_unmeasured", Value::str(why.clone())));
    }
    fields.push((
        "uptime_seconds",
        Value::Integer(i64::try_from(read.uptime_seconds).unwrap_or(i64::MAX)),
    ));
    // **Present or absent, never zero.** Zero idle seconds is a real reading.
    if let Some(idle) = read.idle_seconds {
        fields.push((
            "idle_seconds",
            Value::Integer(i64::try_from(idle).unwrap_or(i64::MAX)),
        ));
    }

    // **`read_from` and `means` come before the boots**, which reads oddly and
    // is not a preference — see [`OUTPUTS`] for the union constraint that fixes
    // it.
    fields.push(("read_from", Value::str(read.source.clone())));
    fields.push(("means", Value::str(means(&read, boots.as_deref().ok()))));

    match &boots {
        Ok(seen) => {
            fields.push(("boots", Value::strings(seen.clone())));
            // The cross-check, made once here so no caller has to know to make
            // it — `get process`'s `userland` argument. It needs both halves,
            // so it is absent rather than guessed when either is.
            if let Some(id) = &read.boot_id {
                fields.push(("recorded", Value::Bool(seen.contains(id))));
            }
        }
        // **Unmeasured, never an empty list.** See `OUTPUTS`.
        Err(e) => fields.push(("boots_unmeasured", Value::str(e.why().to_string()))),
    }

    debug_assert!(
        super::get::in_declared_order(&fields, OUTPUTS.iter().map(|f| f.name)),
        "a get boot result's keys must be a subsequence of OUTPUTS, in order"
    );
    Ok(Value::object(fields))
}

/// **What this reading asserts, and the caveat every timestamp on this hardware
/// inherits.**
///
/// Composed rather than written once, because the sentence that matters changes:
/// a machine whose journal could not be read needs to be told that the missing
/// list is missing rather than empty, and a machine that is not in its own
/// journal needs to be told what that implies.
fn means(read: &super::machine::BootRead, boots: Option<&[String]>) -> String {
    let mut said = String::from(
        "`uptime_seconds` comes off the MONOTONIC counter and is true whether or not this \
         machine's clock has ever been set. NOTHING HERE SAYS WHEN IT BOOTED: ADR-021 gives this \
         hardware no real-time clock, so the wall clock is wrong until something corrects it and \
         then JUMPS — a boot time computed as now-minus-uptime would be exactly as wrong as the \
         clock is. Every timestamp in `get log` inherits the same caveat. ",
    );

    match boots {
        None => said.push_str(
            "The list of boots could NOT be read, which is not the same as this machine having \
             recorded none — see `boots_unmeasured` for what the machine said.",
        ),
        Some(_) if read.boot_id.is_none() => said.push_str(
            "The boots are ordered by the order the journal was APPENDED in, which is the only \
             reliable order there is. This machine could not name its own current boot, so \
             nothing here says which of them is this one.",
        ),
        Some(seen) if read.boot_id.as_ref().is_some_and(|id| seen.contains(id)) => said.push_str(
            "The boots are ordered by the order the journal was APPENDED in, which is the only \
             reliable order there is — not by time, and not by identifier, neither of which \
             orders anything on this hardware. This boot is among them.",
        ),
        Some(_) => said.push_str(
            "The boots are ordered by the order the journal was APPENDED in, which is the only \
             reliable order there is. THIS BOOT IS NOT AMONG THEM, which means nothing has been \
             written to the journal during it — on a booted Rivet that means /state did not \
             mount, or the journal being read is not this machine's.",
        ),
    }

    said
}

