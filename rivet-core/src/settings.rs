//! **What an application was handed** — `ADR-038` §8's file, and its format.
//!
//! The document says what a setting is; `crate::package::application`'s
//! manifest says which settings exist; **this is the shape they arrive in.**
//!
//! # Why a file and not an environment variable or a socket
//!
//! `ADR-038` §8's table, kept because each row is a real cost:
//!
//! | | why not |
//! | :-- | :-- |
//! | an environment variable | fixed at `execve`, so a changed setting needs a restart — and `apply reload` exists precisely to be the lighter answer. Also visible in `/proc` to anything that can read it |
//! | a socket | live updates, at the cost of a protocol, a connection state and a failure mode, for values that change a few times a year |
//! | **a file the application is handed** | survives a restart, is rewritten on reload, is one SDK call |
//!
//! ~~and is the shape `install-secret` already writes~~ — that row's last clause
//! was the reason the file went into `RIVET_APP_DATA`, and it is **struck as of
//! 2026-09-04**: root writing by path below an unprivileged uid's own directory
//! is the shape, and it is the one the audit's CRITICAL symlink truncation came
//! out of. [`path`] has the argument and where the file went.
//!
//! **The variable is still rejected and for the same reason** — a setting
//! changes without a restart. What moved is the file, not the mechanism.
//!
//! # The format is one line per setting, and deliberately dull
//!
//! ```text
//! # Generated by Rivet from the [applications.<name>] table of the
//! # configuration document. Do not edit: this is a view, never an interface.
//! background=digital-rain
//! brightness=60
//! ```
//!
//! **`key=value` with no spaces around the `=`**, and the value runs verbatim
//! to the end of the line. That is not terseness: a key may not contain `=`
//! (`crate::package::application::is_setting_name`), so splitting at the first
//! one is unambiguous — and a value that ran to a delimiter would need quoting,
//! which needs escaping, which is two implementations disagreeing about
//! backslashes. `SPEC-04` §6.2 made the same choice for the same reason.
//!
//! **Sorted by key**, so a machine in one state writes one file. `ADR-007`
//! §3.1's rule, applied one level down.
//!
//! # A value that cannot be written on one line is REPORTED, not mangled
//!
//! `ADR-038` §10.2 keeps values textual for a first version, and TOML can carry
//! a string with a newline in it. Such a value has no place in this format, so
//! [`render`] refuses it **by name** rather than writing something that would
//! read back as two settings. That is `ADR-038` §4.4's rule again, one layer
//! along: reported, ignored, never fatal.

use crate::package::application::is_setting_name;

/// The file, in the application's own tree and **beside `current`**.
///
/// ~~In `data` and therefore writable by the application, which is `ADR-038`
/// §8's recommendation and is worth naming as a cost: an application can
/// overwrite its own settings, and the file is then not what the supervisor
/// wrote.~~ **Superseded 2026-09-04 — see [`path`], and `ADR-038` §8.1.**
pub const FILE: &str = "settings";

/// `<volume>/app/<name>/settings` — **root-owned, application-readable.**
///
/// ~~`<volume>/app/<name>/data/settings`.~~ **Moved 2026-09-04, and the move is
/// about a class of defect rather than about this file.**
///
/// `data/` is the one directory the application owns, at mode `0700` under its
/// own uid (`ADR-015` §3.2A). Writing into it **as root, by path** is the shape
/// that produced the security audit's CRITICAL symlink truncation: an
/// unprivileged program plants a link where root is about to write, and root
/// follows it somewhere else. `O_NOFOLLOW` and the link and FIFO checks closed
/// that instance (`PLAN.md` §123.2 item 2) and left the shape standing, with two
/// users of it — this and `apply install-secret` — which is two examples for the
/// next feature that has to hand an application a file to copy.
///
/// **`<volume>/app/<name>` is root-owned at mode `0755`**
/// (`crate::package::install::DIR_MODE`), created by the installer. An
/// application cannot create anything in it, so there is no link for root to
/// follow and the class is gone rather than guarded.
///
/// Two consequences worth stating rather than discovering:
///
/// * **The application can no longer overwrite its own settings.** The old
///   location cost it exactly that, and the note above named it as a cost. The
///   document is the authority (`ADR-038` §7) and this is a view of it, so the
///   file being unwritable is the view behaving like one — `ADR-007` §3.6.2's
///   *a file that can be written and have effect is not a view*.
/// * **It survives an update and not an uninstall**, which is the same lifetime
///   `data/` has: both are siblings of the version directories, outside
///   `current`, so installing a new version replaces the program and leaves
///   this. `crate::service::data_dir` has the argument.
#[must_use]
pub fn path(volume: &str, name: &crate::service::ServiceName) -> String {
    format!("{}/{FILE}", crate::service::app_dir(volume, name))
}

/// The mode the settings file is written with — `0644`, root-owned.
///
/// **Readable by the application, and by anything else on the machine, and that
/// is not a widening of anything.** It reads narrower than the `0700` the file
/// used to inherit from `data/`, so it is worth saying why the privacy is not
/// being given up: it was never claimed. `ADR-038` §5 chooses a setting's
/// channel by one test — *could this value be committed to a repository the
/// operator shares?* — and everything that answers yes goes in the machine
/// document, into the register, into `git`. A value that answers no is a secret
/// and goes through `apply install-secret` to `data/` at `0600` instead.
///
/// So the old `0700` was a property of where the file happened to live, not a
/// promise anything made about settings. What the mode has to do is let the
/// application read it: a settings file its own uid cannot open is a machine
/// that reports delivery and hands over nothing.
pub const MODE: u32 = 0o644;

/// A value this machine could not hand over, and why.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Rejected {
    pub key: String,
    pub why: &'static str,
}

impl Rejected {
    /// The document names a key the application never declared.
    ///
    /// **This is the check `ADR-038` §3.1 exists for**, and the reason the
    /// declaration is in the manifest at all: without it a misspelled key is
    /// accepted, stored, provisioned to a fleet, and produces an application
    /// that behaves as though it were never set, with nothing reporting it.
    pub const UNDECLARED: &'static str =
        "this application's manifest does not declare that setting, so it would never be read. \
         Check the spelling against `settings` in its manifest, which `rivet explain` can show \
         without running it";

    /// **The key is not a setting at all — it belongs to `[services.<name>]`.**
    ///
    /// Added 2026-09-05, after a port lost a boot to it. `enabled` is the one
    /// key an operator reaches for most and the one place they will not find it
    /// is the table named after the application: an installed application is
    /// switched on under `[services.<name>]`, and `[applications.<name>]` holds
    /// only what that application's own manifest declares (`ADR-038` §3.1).
    ///
    /// [`UNDECLARED`](Self::UNDECLARED) is true of it and is useless, because it
    /// sends the reader to check a spelling that is already right. This one
    /// names the table.
    ///
    /// **It fires only where the manifest is silent**, which is what makes it
    /// safe: an application that genuinely declares a setting called `enabled`
    /// keeps it, and the platform has not narrowed a region whose schema it
    /// explicitly does not own (`ADR-038` §4.3).
    pub const BELONGS_TO_THE_SERVICE: &'static str =
        "this key is not a setting this application declares, and it IS a key of \
         [services.<name>]. To switch an installed application on, write `enabled = true` under \
         [services.<name>]; [applications.<name>] carries only the settings named in the \
         application's own manifest, which `rivet explain` can show without running it";

    /// The value cannot be written on one line.
    pub const NOT_ONE_LINE: &'static str =
        "a setting's value may not contain a newline or a control character - the file is one \
         line per setting (ADR-038 §8), and a value carrying a newline would read back as two \
         settings";
}

/// **Compose the file** an application is handed.
///
/// `declared` is the manifest's list; `values` is what the document says.
/// Returns the text, and everything that was refused with the reason — which
/// the caller journals. A key the application did not declare is **not**
/// written, because writing it would be handing over something nothing reads
/// and calling that delivery.
#[must_use]
pub fn render(declared: &[String], values: &[(String, String)]) -> (String, Vec<Rejected>) {
    let mut kept: Vec<(&str, &str)> = Vec::new();
    let mut rejected = Vec::new();
    for (key, value) in values {
        if !declared.iter().any(|d| d == key) {
            // **Which refusal, and the order matters.** `UNDECLARED` is true of
            // a key that belongs to `[services.<name>]` and tells the reader to
            // go and check a spelling that is already correct. The declaration
            // is consulted FIRST, so an application that does declare `enabled`
            // is unaffected and this only ever speaks where the manifest is
            // silent.
            let why = if crate::service::OPERATOR_KEYS.contains(&key.as_str()) {
                Rejected::BELONGS_TO_THE_SERVICE
            } else {
                Rejected::UNDECLARED
            };
            rejected.push(Rejected {
                key: key.clone(),
                why,
            });
            continue;
        }
        if value.chars().any(|c| c.is_control()) {
            rejected.push(Rejected {
                key: key.clone(),
                why: Rejected::NOT_ONE_LINE,
            });
            continue;
        }
        kept.push((key, value));
    }
    kept.sort_unstable_by(|a, b| a.0.cmp(b.0));

    let mut out = String::from(
        "# Generated by Rivet from the [applications.<name>] table of the configuration\n\
         # document. Do not edit: this is a view of the document, never an interface\n\
         # (ADR-007 §3.6.2). One line per setting, `key=value`, the value verbatim.\n",
    );
    for (key, value) in kept {
        out.push_str(key);
        out.push('=');
        out.push_str(value);
        out.push('\n');
    }
    (out, rejected)
}

/// **Read the file back** — the shape `rivet_sdk::settings` re-declares.
///
/// `#` comments and blank lines are skipped; a line with no `=` is skipped,
/// because a half-written file is better read partially than not at all. Keys
/// that are not [`is_setting_name`] are skipped for the same reason: this is a
/// reader of a file something else wrote, and `crate::json`'s rule is that such
/// a reader is strict about what it accepts and never panics.
#[must_use]
pub fn parse(text: &str) -> Vec<(String, String)> {
    let mut out = Vec::new();
    for line in text.lines() {
        let line = line.trim_end_matches('\r');
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let Some((key, value)) = line.split_once('=') else {
            continue;
        };
        if !is_setting_name(key) {
            continue;
        }
        out.push((key.to_string(), value.to_string()));
    }
    out
}

#[cfg(test)]
mod tests {
    #![allow(clippy::expect_used, clippy::panic, clippy::unwrap_used)]
    use super::*;

    fn declared() -> Vec<String> {
        ["brightness", "background", "show-weather"]
            .into_iter()
            .map(String::from)
            .collect()
    }

    fn values(pairs: &[(&str, &str)]) -> Vec<(String, String)> {
        pairs
            .iter()
            .map(|(k, v)| ((*k).to_string(), (*v).to_string()))
            .collect()
    }

    /// **The property the move of 2026-09-04 exists for**, and the one that
    /// makes it a class fix rather than a relocation: the platform must not
    /// write by path into the directory an unprivileged uid owns.
    ///
    /// `data_dir` is mode `0700` under the application's own uid, so anything
    /// root writes below it is a write an unprivileged program can aim
    /// somewhere else by planting a link first. `app_dir` is root's, mode
    /// `0755`, made by the installer.
    #[test]
    fn the_settings_file_is_not_inside_the_directory_the_application_owns() {
        let name = crate::service::ServiceName::new("aura-renderer").expect("a name");
        let volume = crate::service::BUILT_IN_VOLUME;
        let at = path(volume, &name);

        assert!(
            !at.starts_with(&crate::service::data_dir(volume, &name)),
            "{at} is below the directory the application owns at 0700, so root writing it by \
             path is the shape the audit's symlink truncation came out of"
        );
        // And it is in the application's own tree, beside `current` — so it
        // survives an update and goes when the application does.
        assert_eq!(
            at,
            format!("{}/{FILE}", crate::service::app_dir(volume, &name))
        );
        assert!(!at.contains(crate::service::CURRENT_LINK), "{at}");
    }

    /// The mode has to let the application READ it, or delivery is reported and
    /// nothing arrives. `0644` on a root-owned file in a root-owned directory.
    #[test]
    fn the_mode_is_readable_by_the_application_and_writable_only_by_root() {
        assert_eq!(MODE & 0o200, 0o200, "root could not write it");
        assert_eq!(MODE & 0o044, 0o044, "the application could not read it");
        assert_eq!(MODE & 0o022, 0, "somebody other than root could write it");
    }

    /// What was declared and set is written, sorted, and reads back the same.
    #[test]
    fn a_declared_setting_is_written_and_reads_back_unchanged() {
        let (text, rejected) = render(
            &declared(),
            &values(&[("brightness", "60"), ("background", "digital-rain")]),
        );
        assert!(rejected.is_empty(), "{rejected:?}");
        // Sorted, so one state writes one file.
        let lines: Vec<&str> = text.lines().filter(|l| !l.starts_with('#')).collect();
        assert_eq!(lines, ["background=digital-rain", "brightness=60"]);
        assert_eq!(
            parse(&text),
            values(&[("background", "digital-rain"), ("brightness", "60")])
        );
    }

    /// **A key the application never declared is refused, by name.** This is
    /// the check the whole declaration exists for: without it a misspelling is
    /// provisioned to a fleet and produces an application that behaves as
    /// though nothing were set, with nothing reporting it.
    #[test]
    fn a_key_the_manifest_does_not_declare_is_refused_and_named() {
        let (text, rejected) = render(&declared(), &values(&[("brightnes", "60")]));
        assert_eq!(rejected.len(), 1);
        assert_eq!(rejected[0].key, "brightnes");
        assert_eq!(rejected[0].why, Rejected::UNDECLARED);
        assert!(
            parse(&text).is_empty(),
            "an undeclared key was handed over anyway: {text}"
        );
    }

    /// **The defect a port lost a boot to.** `enabled` under
    /// `[applications.<name>]` is refused — it always was — and the refusal now
    /// names the table it belongs to instead of telling the reader to check a
    /// spelling that is already right.
    #[test]
    fn a_key_that_belongs_to_the_service_table_is_told_which_table() {
        for key in crate::service::OPERATOR_KEYS {
            let (text, rejected) = render(&declared(), &values(&[(key, "true")]));
            assert_eq!(rejected.len(), 1, "{key} was handed over: {text}");
            assert_eq!(rejected[0].key, *key);
            assert_eq!(
                rejected[0].why,
                Rejected::BELONGS_TO_THE_SERVICE,
                "`{key}` earned the generic undeclared message, which sends a reader to \
                 re-check a spelling that is already correct"
            );
            assert!(parse(&text).is_empty(), "{text}");
        }
    }

    /// **And it says where to write it instead**, which is the whole of the
    /// improvement — every word of the old message was true and none of it
    /// named `[services.<name>]`.
    #[test]
    fn that_refusal_names_the_table_and_the_line_to_write() {
        let why = Rejected::BELONGS_TO_THE_SERVICE;
        assert!(why.contains("[services.<name>]"), "{why}");
        assert!(why.contains("[applications.<name>]"), "{why}");
        assert!(why.contains("enabled = true"), "{why}");
        assert!(
            !Rejected::UNDECLARED.contains("[services."),
            "the two refusals must stay distinguishable"
        );
    }

    /// **The declaration wins.** An application whose manifest really does
    /// declare a setting called `enabled` keeps it — this crate has not narrowed
    /// a region whose schema it does not own (`ADR-038` §4.3).
    #[test]
    fn an_application_that_declares_enabled_still_gets_it() {
        let mine: Vec<String> = ["enabled"].into_iter().map(String::from).collect();
        let (text, rejected) = render(&mine, &values(&[("enabled", "yes")]));
        assert!(rejected.is_empty(), "{rejected:?}");
        assert_eq!(parse(&text), values(&[("enabled", "yes")]));
    }

    /// **A value with a newline would read back as two settings**, so it is
    /// refused rather than written.
    #[test]
    fn a_value_that_cannot_be_one_line_is_refused_rather_than_mangled() {
        for bad in ["two\nlines", "a\ttab-is-control", "bell\u{7}"] {
            let (text, rejected) = render(&declared(), &values(&[("brightness", bad)]));
            assert_eq!(rejected.len(), 1, "{bad:?} was written: {text}");
            assert_eq!(rejected[0].why, Rejected::NOT_ONE_LINE);
            assert!(parse(&text).is_empty());
        }
    }

    /// A value may contain anything else, including `=` and spaces — the split
    /// is at the FIRST `=` and a key cannot contain one.
    #[test]
    fn a_value_may_contain_an_equals_sign_and_spaces() {
        let (text, rejected) = render(&declared(), &values(&[("background", "a=b c=d ")]));
        assert!(rejected.is_empty());
        assert_eq!(parse(&text), values(&[("background", "a=b c=d ")]));
    }

    /// An empty value is a value — *set to nothing* is a thing an operator can
    /// mean, and it is not the same as unset.
    #[test]
    fn an_empty_value_survives_and_is_not_the_same_as_absent() {
        let (text, _) = render(&declared(), &values(&[("brightness", "")]));
        assert_eq!(parse(&text), values(&[("brightness", "")]));
        let (empty, _) = render(&declared(), &[]);
        assert!(parse(&empty).is_empty());
    }

    /// The reader is strict about what it accepts and never panics, because it
    /// reads a file something else wrote — `crate::json`'s rule.
    #[test]
    fn the_reader_skips_what_it_cannot_use_rather_than_failing() {
        let text = "# a comment\n\
                    \n\
                    no-equals-sign\n\
                    =novalue\n\
                    BadKey=x\n\
                    with space=x\n\
                    brightness=60\n";
        assert_eq!(parse(text), values(&[("brightness", "60")]));
    }

    /// The header says what it is and what to change instead — `ADR-007`
    /// §3.6.1, and the same header the display window carries.
    #[test]
    fn the_file_says_what_generated_it_and_what_to_change() {
        let (text, _) = render(&declared(), &values(&[("brightness", "60")]));
        assert!(text.starts_with("# Generated by Rivet from"), "{text}");
        assert!(text.contains("never an interface"), "{text}");
        // And the header does not read back as a setting.
        assert_eq!(parse(&text), values(&[("brightness", "60")]));
    }
}
