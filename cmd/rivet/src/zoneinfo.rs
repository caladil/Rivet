//! **The zone names THIS machine's own image can resolve** — R-168, the
//! `timezone` dropdown `ADR-043` §6's Config screen builds from `get
//! schema`.
//!
//! # Why this is here and not in `rivet-config`
//!
//! `rivet-config` performs no I/O (`ADR-014` §3) — its schema is a function
//! of the types, generated identically wherever it runs. A zone database is
//! the opposite of that: it is a property of THIS machine's own image, at
//! `rivet_core::etc::ZONEINFO_DIR`, and two boards on different builds can
//! answer differently. So the reading happens here, at the composition root
//! that already has both a real filesystem and `rivet_config::schema`, and
//! [`rivet_config::schema::with_timezone_zones`] is the pure function that
//! turns the list this module reads into part of the schema `PiMachine`
//! answers with.
//!
//! # Every file is checked, not trusted by its name
//!
//! `cmd/rivet-provision/src/zones.rs`'s `KNOWN` list was generated the same
//! way, off the same database, for the same reason stated there: `zone.tab`,
//! `iso3166.tab`, `tzdata.zi` and `leapseconds` sit beside the real zone files
//! and none of them is one. [`rivet_core::timezone::is_tzfile`] is the same
//! test musl applies, so a name this returns is a name that machine can
//! actually map.
//!
//! # Absence is not a crash
//!
//! [`zone_names`] returns `None` for a directory this build cannot open or
//! read, and `Some(&[])` never happens — an empty database and an absent
//! one are the same answer to a caller, and both mean
//! `configuration_schema` hands back the plain free-text field
//! [`rivet_config::schema::schema`] already builds, never a refusal
//! (`AGENTS.md` §5: refuse rather than guess, and a missing database on an
//! otherwise-working machine is not a reason to refuse the whole subject).

use std::path::Path;

/// **Every zone name this machine's own database carries**, sorted.
///
/// `None` when the directory cannot even be opened — an image built without
/// `rivet-image --zoneinfo`, or a development host with no board filesystem
/// at all. A directory that opens and holds nothing is `Some(Vec::new())`,
/// which [`rivet_config::schema::with_timezone_zones`] already treats the
/// same way — both leave the field as the plain free-text `schema()` built.
#[must_use]
pub fn zone_names() -> Option<Vec<String>> {
    let root = Path::new(rivet_core::etc::ZONEINFO_DIR);
    let mut out = Vec::new();
    walk(root, root, &mut out).ok()?;
    out.sort_unstable();
    Some(out)
}

/// Recurse one directory, appending every real tzfile's name relative to
/// `root` — `"America/Chicago"`, not the path on disk.
fn walk(root: &Path, dir: &Path, out: &mut Vec<String>) -> std::io::Result<()> {
    for entry in std::fs::read_dir(dir)? {
        let entry = entry?;
        let file_type = entry.file_type()?;
        let path = entry.path();
        if file_type.is_dir() {
            walk(root, &path, out)?;
            continue;
        }
        if !file_type.is_file() {
            continue;
        }
        let Ok(bytes) = std::fs::read(&path) else {
            // Unreadable is not the same claim as absent — skip this one
            // file rather than failing the whole walk over it.
            continue;
        };
        if !rivet_core::timezone::is_tzfile(&bytes) {
            continue;
        }
        if let Ok(relative) = path.strip_prefix(root) {
            // `to_string_lossy` rather than refuse a non-UTF-8 path: this
            // machine's own database, generated by this project's own build
            // (`ADR-003` §4), is not expected to carry one — and a name this
            // build cannot even print is a name that belongs off the list,
            // not a reason to stop reading the rest of it.
            let name = relative.to_string_lossy().replace('\\', "/");
            out.push(name);
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    // A test that cannot fail loudly is not a test.
    #![allow(clippy::expect_used, clippy::panic, clippy::unwrap_used)]

    use super::*;

    /// A tzfile, byte for byte enough to pass [`rivet_core::timezone::is_tzfile`]
    /// — the magic and forty bytes of padding, nothing else. What matters
    /// here is the file NAME, not its contents.
    fn tzfile_bytes() -> Vec<u8> {
        let mut bytes = b"TZif".to_vec();
        bytes.resize(rivet_core::timezone::MIN_TZFILE_BYTES, 0);
        bytes
    }

    /// A scratch directory shaped like a real zoneinfo tree: real tzfiles
    /// under nested directories, and the non-tzfile companions a real
    /// database ships beside them — `zone.tab` is not a zone.
    fn scratch_database() -> std::path::PathBuf {
        let dir = std::env::temp_dir().join(format!(
            "rivet-zoneinfo-test-{}-{:?}",
            std::process::id(),
            std::thread::current().id()
        ));
        let america = dir.join("America");
        std::fs::create_dir_all(&america).expect("create scratch dir");
        std::fs::write(america.join("Chicago"), tzfile_bytes()).expect("write");
        std::fs::write(dir.join("UTC"), tzfile_bytes()).expect("write");
        std::fs::write(dir.join("zone.tab"), b"not a tzfile at all").expect("write");
        dir
    }

    /// **A real tzfile nested under a directory is found, by its relative
    /// name** — `America/Chicago`, not `Chicago` and not the path on disk.
    #[test]
    fn a_nested_tzfile_is_found_by_its_relative_name() {
        let dir = scratch_database();
        let mut out = Vec::new();
        walk(&dir, &dir, &mut out).expect("walk");
        out.sort_unstable();
        assert_eq!(out, vec!["America/Chicago".to_owned(), "UTC".to_owned()]);
        std::fs::remove_dir_all(&dir).ok();
    }

    /// **A file that is not a tzfile is left out**, whatever its name looks
    /// like — `zone.tab` sits beside real zones in a real database and is not
    /// one, exactly the case `cmd/rivet-provision/src/zones.rs`'s own
    /// generation script filters the same way.
    #[test]
    fn a_non_tzfile_companion_is_not_offered_as_a_zone() {
        let dir = scratch_database();
        let mut out = Vec::new();
        walk(&dir, &dir, &mut out).expect("walk");
        assert!(!out.iter().any(|z| z.contains("zone.tab")), "{out:?}");
        std::fs::remove_dir_all(&dir).ok();
    }

    /// **An absent database is `None`, not an empty list and not
    /// a panic.** The two read differently to a caller: `None` says "this
    /// machine has no database to check against", `Some(vec![])` would claim
    /// a database that opened and genuinely held nothing.
    #[test]
    fn a_missing_database_is_none_rather_than_a_crash() {
        let dir = std::env::temp_dir().join(format!(
            "rivet-zoneinfo-test-missing-{}-{:?}",
            std::process::id(),
            std::thread::current().id()
        ));
        // Deliberately not created.
        let mut out = Vec::new();
        assert!(walk(&dir, &dir, &mut out).is_err());
    }
}
